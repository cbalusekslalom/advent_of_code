def build_order_dictionary(input_list)->dict:
    # assume input list is the processed 
    output_dictionary = defaultdict()
    for value in input_list:
        split_value = value.split('|')
        if split_value[0] not in output_dictionary.keys():
            output_dictionary[split_value[0]] = []
        if split_value[1] not in output_dictionary.keys():
            output_dictionary[split_value[1]] = []
        output_dictionary[split_value[0]].append(split_value[1])
    #print({key:len(output_dictionary[key]) for key in output_dictionary.keys()})
    return output_dictionary


def list_comp(l1, l2) -> bool:
    for x in l1:
        if x not in l2:
            return False 
    return True
    

def test_list(inpList:list, input_dict:dict) -> bool:
    if len(inpList) == 1:
        return True
    key = inpList[0]
    rem_list = inpList[1:]
    dict_check = list_comp(rem_list, input_dict[key])
    return dict_check and test_list(rem_list, input_dict)
    # compare the 0th index key to [1:] 
    # for list index i [0:len(list)]
    # check that [i+1:] are all in the output dictionary value for dict[i]


def check_elements(e1, e2, dic):
    if e2 in dic[e1]:
        return True 
    else:
        return False


def test_list_2(inpList:list, input_dict:dict) -> bool:
    ## check i against i+1 
    ## if true, check i+1 else switch i <-> i+1 and check i agianst i+2 -> add note to check i+1 against i-1
    ## 0 vs 1 -> if inpList[i+1] in input_dict[inpList[i]] -> pass 
    ## 0 vs 1 -> if inpList[i+1] not in input_dict[inpList[i]] -> inpList[i], inputLList[i+1] = inputLList[i+1], inpList[i]
    ## 0, 1, 2, 3, 4, 5
    idx = 0
    while idx < len(inpList)-1:
        if inpList[idx+1] not in input_dict[inpList[idx]]:
            # reverse direction, hold idx
            inpList[idx], inpList[idx+1] = inpList[idx+1], inpList[idx]
            idj = idx
            while not check_elements(inpList[idj-1], inpList[idj], input_dict) and idj > 0:
                inpList[idj], inpList[idj-1] = inpList[idj-1], inpList[idj]
                idj -= 1
                if idj == 0:
                    continue
        else:
            idx += 1
    return inpList
    # compare the 0th index key to [1:] 
    # for list index i [0:len(list)]
    # check that [i+1:] are all in the output dictionary value for dict[i]


def read_file(inFile):
    with open(inFile) as f:
        firstlines = True
        rules, lists  = [], []
        for line in f.readlines():
            if line == '\n':
                firstlines = False
                continue
            if firstlines:
                rules.append(line.strip())
            else:
                lists.append(line.strip())

    return rules, lists


